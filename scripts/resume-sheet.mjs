#!/usr/bin/env node
/**
 * Renders the résumé sheet to a PDF and records its golden text extraction
 * (issue #183, epic #180).
 *
 * WHY A SCRIPT AND NOT THE WORKER. src/lib/resume-pdf.ts renders at runtime
 * from a Browser Run binding, and the epic's argument for moving off it is that
 * the PDF is a pure function of the commit: every input is repo content, so
 * runtime rendering buys nothing and charges three things. It put the artifact
 * where no test can see it, which is how a contact-free PDF shipped and stayed
 * shipped. It introduced a deploy race that froze the live file. And it bills
 * browser-minutes for a document that changes a few times a year. This script
 * is the first half of the replacement; 05 moves it into GitHub Actions and
 * publishes to R2, and only 06 retires the runtime path.
 *
 * WHAT IT DOES. Serves the already-built `dist/client` on an ephemeral port,
 * drives a local headless Chrome over CDP, waits for `data-resume-ready`,
 * prints, stamps metadata with src/lib/resume-pdf-metadata.ts, and writes two
 * outputs: the PDF, which is gitignored because it belongs in R2, and the
 * golden extraction, which is committed because it is what review reads.
 *
 * THE BUILD IS NOT RUN HERE. `npm run resume:pdf` is `astro build && node
 * scripts/resume-sheet.mjs`, the same shape as `npm test`. That keeps the build
 * where a reader already looks for it, and lets CI (04) call this file directly
 * after the build it has already paid for rather than doing it twice.
 *
 * NO PUPPETEER. `@cloudflare/puppeteer` is a Workers client for a Browser Run
 * binding, not a local launcher, and it cannot drive a Chrome on this machine.
 * Adding `puppeteer` proper would pull a ~170 MB browser download into every
 * install of this repo to save perhaps eighty lines of CDP. The protocol below
 * is five commands.
 */
