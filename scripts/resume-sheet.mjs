/**
 * `CHROME_PATH` first so a runner can name its own browser -- that is the
 * variable GitHub Actions' setup-chrome and browser-actions both export, and 05
 * relies on it. The rest are the install locations that actually occur: macOS
 * puts Chrome in either /Applications or ~/Applications depending on whether it
 * was installed for all users, and this machine has the second (measured
 * 2026-09-15, Chrome 152).
 *
 * Named for what these ARE -- paths to a browser binary -- rather than for the
 * part they play in the search below. tests/tier-invisibility.test.ts scans
 * `scripts` for the vocabulary the private tier keeps off public surfaces, and
 * the obvious word for "the one being considered" is on that list.
 * src/lib/corpus.ts holds the one registered exception to it, earned because
 * there the word is the clearest one available; here `executable` is clearer
 * than the word it replaces, so this file earns nothing and needs nothing.
 */
function chromePaths() {
  return [
    process.env.CHROME_PATH,
    process.env.PUPPETEER_EXECUTABLE_PATH,
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    join(homedir(), 'Applications/Google Chrome.app/Contents/MacOS/Google Chrome'),
    '/Applications/Chromium.app/Contents/MacOS/Chromium',
    '/usr/bin/google-chrome',
    '/usr/bin/google-chrome-stable',
    '/usr/bin/chromium',
    '/usr/bin/chromium-browser',
  ].filter(Boolean);
}

async function findChrome() {
  for (const executable of chromePaths()) {
    try {
      if ((await stat(executable)).isFile()) return executable;
    } catch {
      // Not there. Moving to the next path is the whole recovery.
    }
  }
  throw new Error(
    `no Chrome found. Tried:\n  ${chromePaths().join('\n  ')}\n` +
      'Set CHROME_PATH to the binary to use.',
  );
}

/**
 * Launches headless Chrome on an ephemeral debugging port and resolves the
 * WebSocket endpoint it prints to stderr.
 *
 * Port 0 rather than a fixed port: two runs of this script, or a run alongside
 * a developer's own debugging session, must not collide. Chrome answers by
 * printing the port it actually took, which is the line parsed below.
 *
 * The user-data-dir is a fresh temp directory every time. Without it Chrome
 * attaches to the profile the human is browsing in, which means their
 * extensions, their cookies and their open tabs are all in the render.
 */
async function launchChrome(executable) {
  const profile = await mkdtemp(join(tmpdir(), 'resume-sheet-'));
  const child = spawn(
    executable,
    [
      '--headless=new',
      '--remote-debugging-port=0',
      `--user-data-dir=${profile}`,
      '--no-first-run',
      '--no-default-browser-check',
      '--disable-extensions',
      '--hide-scrollbars',
      // Print output is sRGB; letting Chrome adopt the display profile makes
      // the same commit render different bytes on different machines.
      '--force-color-profile=srgb',
      // GitHub's runners run as a user whose sandbox Chrome refuses to start
      // under. Only there: dropping the sandbox on a developer's own machine
      // to render a local file would be a real loss for no gain.
      ...(process.env.CI ? ['--no-sandbox'] : []),
    ],
    { stdio: ['ignore', 'ignore', 'pipe'] },
  );

  const endpoint = await new Promise((resolvePromise, rejectPromise) => {
    let stderr = '';
    const timer = setTimeout(() => {
      rejectPromise(new Error(`Chrome did not report a DevTools endpoint:\n${stderr}`));
    }, 30_000);

    child.stderr.on('data', (chunk) => {
      stderr += chunk;
      const match = stderr.match(/ws:\/\/[^\s]+/);
      if (match) {
        clearTimeout(timer);
        resolvePromise(match[0]);
      }
    });
    child.once('error', (error) => {
      clearTimeout(timer);
      rejectPromise(error);
    });
    child.once('exit', (code) => {
      clearTimeout(timer);
      rejectPromise(new Error(`Chrome exited with ${code} before listening:\n${stderr}`));
    });
  });

  return {
    endpoint,
    /*
     * The wait for `exit` before removing the profile is not politeness. Chrome
     * is still flushing its Default/ subtree when SIGTERM arrives, so removing
     * the directory straight after `kill()` loses the race and throws
     * ENOTEMPTY -- measured 2026-09-15 on the first run of this script, after
     * the PDF had already been rendered. The removal is also best-effort: a
     * temp directory that outlives one run is the operating system's problem,
     * and failing the render over it would throw away the artifact.
     */
    async close() {
      const exited = new Promise((resolvePromise) => child.once('exit', resolvePromise));
      child.kill();
      await exited;
      await rm(profile, { recursive: true, force: true }).catch(() => {});
    },
  };
}

/**
 * The smallest CDP client that does this job: correlate replies by id, route
 * events by method, and nothing else.
 *
 * `flatten: true` on the attach below is what lets one socket carry both the
 * browser session and the page session, distinguished by `sessionId`. The
 * alternative, a second WebSocket to the page target, is the older protocol
 * shape and buys nothing here.
 */
class Cdp {
  #socket;
  #nextId = 1;
  #pending = new Map();
  #listeners = new Set();

  constructor(socket) {
    this.#socket = socket;
    socket.addEventListener('message', (event) => {
      const message = JSON.parse(event.data);
      if (message.id !== undefined) {
        const entry = this.#pending.get(message.id);
        if (!entry) return;
        this.#pending.delete(message.id);
        if (message.error) entry.reject(new Error(`${entry.method}: ${message.error.message}`));
        else entry.resolve(message.result);
        return;
      }
      for (const listener of this.#listeners) listener(message);
    });
  }

  static async connect(endpoint) {
    const socket = new WebSocket(endpoint);
    await new Promise((resolvePromise, rejectPromise) => {
      socket.addEventListener('open', resolvePromise, { once: true });
      socket.addEventListener('error', () => rejectPromise(new Error('CDP socket failed')), {
        once: true,
      });
    });
    return new Cdp(socket);
  }

  send(method, params = {}, sessionId) {
    const id = this.#nextId++;
    return new Promise((resolvePromise, rejectPromise) => {
      this.#pending.set(id, { method, resolve: resolvePromise, reject: rejectPromise });
      this.#socket.send(JSON.stringify({ id, method, params, ...(sessionId && { sessionId }) }));
    });
  }

  /** Resolves on the next matching event. Registered before the command that causes it. */
  once(method, sessionId) {
    return new Promise((resolvePromise) => {
      const listener = (message) => {
        if (message.method !== method) return;
        if (sessionId && message.sessionId !== sessionId) return;
        this.#listeners.delete(listener);
        resolvePromise(message.params);
      };
      this.#listeners.add(listener);
    });
  }

  close() {
    this.#socket.close();
  }
}

